"""
Phishing Email Analyser: the case note.

At the end of an investigation the analyst writes it up in a ticket: what
the email was, why it's bad, the indicators, and what should happen next.
This builds that write-up as plain text, so it pastes cleanly into any
ticketing system (ServiceNow, Jira, TheHive, a shared mailbox).

Everything from the email is defanged, so nothing in the note is clickable.
"""

import re
from datetime import datetime, timezone

from . import __version__
from .attachments import PROBLEM_LABELS as ATTACH_LABELS
from .ioc import defang
from .links import PROBLEM_LABELS as LINK_LABELS
from .phishing import EmailReport, domain_of

ACTIONS = {
    "Likely phishing": [
        "Treat as phishing. Do not click links or open attachments.",
        "Block the sender's domain and the sending IP at the email gateway.",
        "Block the link domains at the web proxy or DNS filter.",
        "Search all mailboxes for the same email (subject, sender or attachment hash) and remove it.",
        "Check proxy and endpoint logs for anyone who clicked a link or opened an attachment.",
        "If anyone entered a password, reset it, end their active sessions and check for new mailbox rules.",
    ],
    "Suspicious": [
        "Treat with caution. Do not click links or open attachments yet.",
        "Confirm with the sender using a contact method you already trust, not details from this email.",
        "Escalate if the email asks for a password, payment, bank details or urgent action.",
    ],
    "No red flags found": [
        "No action needed based on the technical checks.",
        "If the email asks for money, passwords or urgent action, confirm with the sender another way first.",
    ],
}


def _one_line(text: str) -> str:
    return " ".join((text or "").split())


EMAIL_RE = re.compile(r"([\w.+-]+@)([\w-]+(?:\.[\w-]+)+)")
URL_RE = re.compile(r"(?:https?://|www\.)\S+", re.I)


def _defang_text(text: str, domains: set[str]) -> str:
    """
    Defang links, email addresses and known domains in free text, so a
    ticketing system can't turn them into clickable links.
    """
    text = URL_RE.sub(lambda m: defang(m.group(0)), _one_line(text))
    text = EMAIL_RE.sub(lambda m: m.group(1) + m.group(2).replace(".", "[.]"), text)
    for d in sorted(domains, key=len, reverse=True):
        text = re.sub(rf"(?<![\w.\[]){re.escape(d)}(?![\w-])", d.replace(".", "[.]"), text)
    return text


def _domains(report: EmailReport) -> set[str]:
    found = {report.from_domain, domain_of(report.reply_to), domain_of(report.return_path)}
    found |= {l.host for l in report.links}
    return {d for d in found if d and "." in d}


def build_case_note(report: EmailReport, intel_rows: list | None = None, when: datetime | None = None) -> str:
    when = when or datetime.now(timezone.utc)
    domains = _domains(report)
    safe = lambda text: _defang_text(text, domains) if text else "(none)"  # noqa: E731
    auth = " | ".join(f"{m.upper()} {report.auth[m][0]}" if m in report.auth else f"{m.upper()} not reported"
                      for m in ("spf", "dkim", "dmarc"))
    sender = f"{report.from_name} <{report.from_address}>" if report.from_name else report.from_address

    lines = [
        "PHISHING ANALYSIS - CASE NOTE",
        f"Generated by SOC Toolkit v{__version__} on {when:%d %b %Y %H:%M} UTC",
        "",
        f"VERDICT: {report.verdict} (risk score {report.score}/100)",
        "",
        "RECOMMENDED ACTION",
        *[f"- {a}" for a in ACTIONS[report.verdict]],
        "",
        "EMAIL",
        f"Subject:      {_one_line(report.subject) or '(none)'}",
        f"From:         {safe(sender)}",
        f"Reply-To:     {safe(report.reply_to)}",
        f"Return-Path:  {safe(report.return_path)}",
        f"To:           {safe(report.to)}",
        f"Date:         {_one_line(report.date) or '(none)'}",
        f"Message-ID:   {_one_line(report.message_id) or '(none)'}   (as sent, for searching mailboxes)",
        f"Auth results: {auth}",
        f"Sending IP:   {defang(report.origin_ip) if report.origin_ip else '(not found)'}",
        "",
        "RED FLAGS",
    ]
    scored = sorted([f for f in report.flags if f.points], key=lambda f: -f.points)
    lines += [f"- [+{f.points}] {f.area}: {f.title}. {safe(f.why)}" for f in scored] or ["- None found."]

    lines += ["", "INDICATORS (defanged)"]
    if report.origin_ip:
        lines.append(f"Sending IP:  {defang(report.origin_ip)}")
    hosts = sorted({l.host for l in report.links if l.host})
    if hosts:
        lines.append("Domains:     " + ", ".join(defang(h) for h in hosts))
    for link in report.links:
        problems = f"  <- {', '.join(LINK_LABELS[p] for p in link.problems)}" if link.problems else ""
        lines.append(f"URL:         {defang(_one_line(link.url))}{problems}")
    for att in report.attachments:
        problems = f"  <- {', '.join(ATTACH_LABELS[p] for p in att.problems)}" if att.problems else ""
        lines.append(f"Attachment:  {_one_line(att.name).replace(chr(0x202e), '[hidden character]')} "
                     f"({att.real_type}, {att.size} bytes){problems}")
        lines.append(f"  SHA256:    {att.sha256}")
        lines.append(f"  MD5:       {att.md5}")
    if not (report.origin_ip or report.links or report.attachments):
        lines.append("- None found.")

    lines += ["", "THREAT INTELLIGENCE"]
    if intel_rows:
        for row in intel_rows:
            scored_results = [x for x in row["results"] if x["score"] is not None]
            bad = sum(x["score"] >= 50 for x in scored_results)
            best = max(scored_results, key=lambda x: x["score"]) if scored_results else None
            value = row["value"] if row["type"] == "sha256" else defang(row["value"])
            finding = f" - {best['provider']}: {safe(best['summary'])}" if best else " - no source had data"
            lines.append(f"- {row['role']} {value}: {row['verdict']} "
                         f"({bad} of {len(scored_results)} sources){finding}")
    else:
        lines.append("- Not run. Use \"Check with threat intelligence\" to add it.")

    lines += ["", "ANALYST NOTES", "- ", ""]
    return "\n".join(lines)
